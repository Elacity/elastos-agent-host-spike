//! Census of production code entries that start or prepare executable bytes.
//! Each row names its authority inputs as they are today. A source call without
//! a row and a row whose enclosing function moves both fail this test.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;

use crate::start_census_tests as source;

struct Row {
    file: &'static str,
    function: &'static str,
    call: String,
    kind: &'static str,
    checks: &'static str,
    check_id: &'static str,
    count: usize,
}

fn row(
    file: &'static str,
    function: &'static str,
    call: impl Into<String>,
    kind: &'static str,
    checks: &'static str,
    check_id: &'static str,
    count: usize,
) -> Row {
    Row {
        file,
        function,
        call: call.into(),
        kind,
        checks,
        check_id,
        count,
    }
}

