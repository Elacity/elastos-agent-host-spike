//! wc-001 capsule: a minimal core Wasm module that, since task 068, is also a
//! real `product-capsule-v1` capsule of `elastos:bus@1.0.0`.
//!
//! This is the lab's foundation. The capsule is a small self-contained computer
//! (Rong's "DigitCapsule"): one flat linear memory, its logic compiled in, and
//! no imports — it traps down to nothing. It exports `digest`, so later tasks
//! can hash-name it (wc-003), sign that name (wc-004) and run it unchanged on
//! two engines (wc-005), and it exports the world's `lifecycle.run` through
//! `wit-bindgen`, so the Runtime's componentize wraps it into a component.
//!
//! `digest_impl` is the single shared implementation. The Wasm export and the
//! host test both call it, so there is one path for the capsule's behaviour
//! (PRINCIPLES P10): no second copy of the rule.
//!
//! The capsule uses `std` on wasm32, as the Runtime's own component-app
//! template does (task 068, measured in 067): `no_std` cannot hold, because
//! the generated bindings need a global memory allocator and cargo refuses a
//! `no_std` cdylib with "no global memory allocator found but one is
//! required". The guest still calls no import; `std` here supplies the
//! allocator the generated code needs, nothing else.

/// A fixed input for the host test. Its expected output is pinned as a literal
/// in [`FIXED_OUTPUT`], so a change to [`digest_impl`] is caught.
pub const FIXED_INPUT: u32 = 0x5EED_0001;

/// The pinned value of `digest_impl(FIXED_INPUT)`, written as a literal and not
/// derived from `digest_impl`, so the test is not a tautology.
pub const FIXED_OUTPUT: u64 = 0x0331_7BB4_875F_B038;

/// The capsule's one pure operation, shared by the Wasm export and the host
/// test. A splitmix64-style mix: total (no panics), deterministic, `core`-only.
pub const fn digest_impl(n: u32) -> u64 {
    let mut z = (n as u64).wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// The capsule's core-Wasm export: `(param i32) -> (result i64)` (`u32`
/// lowers to `i32`, `u64` to `i64`).
#[cfg(target_arch = "wasm32")]
#[no_mangle]
pub extern "C" fn digest(n: u32) -> u64 {
    digest_impl(n)
}

// Task 068 (carry of 067): the world the Runtime's componentize wraps into a
// `product-capsule-v1` component of `elastos:bus@1.0.0`, generated by the same
// crate and the same call the Runtime's own component-app template uses
// (`templates/capsules/component-app/src/lib.rs`). `../../elastos/wit` is the
// repo's WIT folder from this lane root, and `product-capsule-v1` is
// `elastos/wit/elastos-bus-v1.wit:90`. The bindings are wasm32-only: the host
// test build links without them.
#[cfg(target_arch = "wasm32")]
wit_bindgen::generate!({
    path: "../../elastos/wit",
    world: "product-capsule-v1",
});

/// The one guest the world exports (task 068).
#[cfg(target_arch = "wasm32")]
struct Capsule;

/// Rong's contract (28 Oct): `lifecycle.run` is one bounded run,
/// `func() -> result<_, bus-error>` (`elastos/wit/elastos-bus-v1.wit:84-87`).
/// This capsule's run does nothing and calls no import, so it gains no
/// authority: it returns `Ok(())` and never constructs an error.
#[cfg(target_arch = "wasm32")]
impl exports::elastos::bus::lifecycle::Guest for Capsule {
    fn run() -> Result<(), elastos::bus::types::BusError> {
        Ok(())
    }
}

#[cfg(target_arch = "wasm32")]
export!(Capsule);

#[cfg(test)]
mod tests {
    use super::{digest_impl, FIXED_INPUT, FIXED_OUTPUT};

    #[test]
    fn digest_returns_the_fixed_value() {
        assert_eq!(digest_impl(FIXED_INPUT), FIXED_OUTPUT);
    }
}
